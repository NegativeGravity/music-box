NAMES = ['After Hours','Soft Signal','Blue Hour','Night Drive','Quiet Motion','Parallel Lines','Warm Static','Slow Orbit',
         'City Lights','Late Check-in','Paper Skies','Lost Frequency','Velvet Morning','Second Sun','Small Hours','Still Here',
         'Open Window','Daydream Loop','Past Midnight','Silver Lining','Home Again','Summer Notes','Neon Bloom','Golden Air',
         'Floating Away','First Light','Rain on Glass','Gentle Waves','Distant Shore','Another Morning','Calm Current','Sunday Slow']


def synth(index, genre, seconds=32):
    sr=22050
    t=np.arange(sr*seconds)/sr
    rng=np.random.default_rng(index+190)
    bpm={'Electronic':112,'Hip-Hop':82,'Pop':104,'Instrumental':65}[genre]
    beat=60/bpm
    signal=np.zeros_like(t)
    root=[48,50,53,55,57,60,62,65][index%8]
    for bar in range(int(seconds/(beat*4))+1):
        start=bar*beat*4
        mask=(t>=start)&(t<start+beat*4)
        local=t[mask]-start
        for note in [root+[0,-3,5,7][bar%4],root+[0,-3,5,7][bar%4]+7,root+[0,-3,5,7][bar%4]+12]:
            frequency=440*2**((note-69)/12)
            envelope=np.minimum(local/.12,1)*np.minimum((beat*4-local)/.35,1)
            signal[mask]+=(.08*np.sin(2*np.pi*frequency*local)+.025*np.sin(2*np.pi*frequency*2*local))*envelope
    for n,start in enumerate(np.arange(0,seconds,beat/2)):
        end=min(len(t),int((start+.4)*sr)); begin=int(start*sr)
        local=np.arange(end-begin)/sr
        note=root+12+[0,7,12,7,3,7,10,7][(n+index)%8]
        freq=440*2**((note-69)/12)
        signal[begin:end]+=.085*np.sin(2*np.pi*freq*local)*np.exp(-local*9)
        if genre!='Instrumental':
            if n%8 in [0,4]:
                phase=2*np.pi*(48*local+38*(1-np.exp(-local*24))/24)
                signal[begin:end]+=.25*np.sin(phase)*np.exp(-local*18)
            if n%8 in [2,6]:
                noise=rng.normal(0,1,len(local))
                signal[begin:end]+=.055*noise*np.exp(-local*38)
            signal[begin:end]+=.018*rng.normal(0,1,len(local))*np.exp(-local*110)
    delay=sr//4
    signal+=.10*np.r_[np.zeros(delay),signal[:-delay]]
    fade=np.minimum(t/.8,1)*np.minimum((seconds-t)/1.4,1)
    signal=np.tanh(signal*1.4)*fade
    raw=(np.clip(signal,-1,1)*26000).astype('<i2')
    stream=io.BytesIO()
    with wave.open(stream,'wb') as output:
        output.setnchannels(1);output.setsampwidth(2);output.setframerate(sr);output.writeframes(raw.tobytes())
    return stream.getvalue()


def seed_demo(service):
    with service.Session() as db:
        existing={t.title for t in db.scalars(select(Track).where(Track.source=='demo'))}
    count=0
    for index,title in enumerate(NAMES):
        if title in existing:
            continue
        genre=['Electronic','Hip-Hop','Pop','Instrumental'][index//8]
        service.add_shared_track(title, ['Studio North','Quiet Assembly','Nocturne Lab','Soft Circuit'][index//8],genre,synth(index,genre),source='demo',provenance='Original synthesized preview audio generated by Musicbox. Not commercial music or FMA.')
        count+=1
    return count


